"""Generate docs/05_specifications.md and docs/06_review_response.md from code and content.

Usage: .venv/bin/python scripts/build_docs.py
"""
import json
import sys

import _bootstrap  # noqa: F401

from midterm_quant import config
from midterm_quant.data import catalog
from midterm_quant.research.monitor import ORDER, ORIGINAL_33, SPECS
from midterm_quant.specs import COMMON_INVALIDATION, all_specs
from midterm_quant import specs as specs_mod

sys.path.insert(0, str(config.ROOT))
from site_src import content as C  # noqa: E402

DOCS = config.ROOT / "docs"


def md_escape(s: str) -> str:
    return str(s).replace("|", "\\|")


def specs_doc() -> str:
    out = ["# Specifications: 36 indicators and 20 strategies", "",
           "Generated by `scripts/build_docs.py` from `midterm_quant/research/monitor.py`, `midterm_quant/specs.py`, the strategy classes and the data catalogue (`midterm_quant/data/catalog.py`). Do not edit by hand.", "",
           "## Shared rules", "", specs_mod.__doc__.split("Shared execution rules (engine/base.py), true for every strategy:")[1].strip(), "",
           "## Indicators", "",
           f"{len(ORDER)} indicators: the {len(ORIGINAL_33)} declared on 4 Nov 2026 (several renamed on 6 Nov to say what they measure) and 3 direct measures added on 6 Nov (M11, M12, N-f). Thresholds were fixed before any reading was taken.", ""]
    for code in ORDER:
        s = SPECS[code]
        inputs = []
        for name in s.inputs:
            if name in ("ZQ contracts", "CL contracts"):
                inputs.append(f"{name} (Yahoo individual CME contracts; current curve only)")
                continue
            m = catalog.meta(name)
            inputs.append(f"`{name}`: {m.units}; {m.frequency}; released {m.release}; usable by rule `{m.available_rule}`; revisions {m.revisions}")
        out += [f"### {code}: {s.name}", "",
                f"- **Measures:** {s.measures}.", f"- **Limits:** {s.not_measures}.",
                f"- **Formula:** {s.formula}.", f"- **Units / frequency:** {s.units}; {s.frequency}.",
                f"- **Rule (declared {s.declared}):** {s.rule}.",
                "- **Inputs:** " + ("; ".join(inputs) if inputs else "calendar only") + ".",
                f"- **Missing or stale data:** {s.missing}",
                f"- **Direct measure:** {s.better}." if s.better else "- **Direct measure:** this is the direct measure.", ""]
    out += ["## Strategies", "", f"Common prospective invalidation rule: {COMMON_INVALIDATION}", ""]
    for s in all_specs():
        out += [f"### {s['code']}: {s['name']} ({s['class']}, {s['version']}, evidence {s['evidence']})", "",
                f"- **Thesis:** {s['thesis']}", f"- **Signal:** {s['signal']}", f"- **Entry / sizing:** {s['entry']}", f"- **Exit:** {s['exit']}",
                f"- **Calendar and timing:** {s['calendar']}; decision at the {s['decision_time']}; {s['execution']}; warm-up {s['warmup_bars']} bars; trading from {s['trading_starts']}; max long {s['max_long']:.0%}, max gross {s['max_gross']:.0%}; minimum trade {s['min_trade']:.0%} of equity.",
                "- **Inputs:**"]
        for i in s["inputs"]:
            out.append(f"  - `{i['series']}` ({i['role']}): {i['units']}; {i['frequency']}; released {i['release']}; rule `{i['available_rule']}`; revisions {i['revisions']}")
        out += [f"- **Parameters:** `{json.dumps(s['parameters'])}`", f"- **Parameter provenance:** {s['provenance']}",
                f"- **Missing data:** {s['missing_data']}", f"- **Benchmarks:** reference `{s['benchmark_reference']}`; primary comparison {s['benchmark_primary']}; also cash, buy-and-hold and a 10-month trend rule.",
                f"- **Invalidation:** {s['invalidation']}", ""]
    return "\n".join(out)


def review_doc() -> str:
    out = ["# Review response: finding, change, evidence", "",
           "Response to the external review of 6 Nov 2026. Generated by `scripts/build_docs.py` from `site_src/content.py`; evidence paths are relative to the repository root at the commit named in `reports/results/results.json`.", "",
           f"> {C.NOT_RECEIVED}", "",
           "| Item | Finding | Change | Evidence | Status | Still missing (data, environment or permission) |", "|---|---|---|---|---|---|"]
    for m in C.MATRIX:
        out.append(f"| {m['id']} | {md_escape(m['finding'])} | {md_escape(m['change'])} | {'<br>'.join(f'`{p}`' for p in m['evidence'])} | **{m['status']}** | {md_escape(m['missing']) or '-'} |")
    out += ["", "## Acceptance deliverables", "", "| Deliverable | Location |", "|---|---|"]
    out += [f"| {a} | `{b}` |" for a, b in C.DELIVERABLES]
    out += ["", "## Unfinished items, named precisely", ""]
    for m in C.MATRIX:
        if m["missing"]:
            out.append(f"- **{m['id']}:** {m['missing']}")
    out += ["- **Independent reproduction:** a third party must run `scripts/reproduce.sh` (and `scripts/verify_data.py` against the committed manifest); not yet done.",
            "- **Forward paper trading:** starts with the first decision after the freeze (see `docs/07_validation_plan.md`); no records exist yet.", ""]
    return "\n".join(out)


def fill_block(text: str, tag: str, body: str) -> str:
    a = text.index(f"<!-- BEGIN {tag}")
    a = text.index("-->", a) + 3
    b = text.index(f"<!-- END {tag} -->")
    return text[:a] + "\n" + body + "\n" + text[b:]


def framework_blocks() -> None:
    from midterm_quant.research.scenarios import SCENARIOS

    p = DOCS / "02_observation_framework.md"
    t = p.read_text()
    rows = ["| Code | Group | Indicator | Formula | Rule (declared) |", "|---|---|---|---|---|"]
    for code in ORDER:
        s = SPECS[code]
        rows.append(f"| {code} | {s.group} | {md_escape(s.name)} | {md_escape(s.formula)} | {md_escape(s.rule)} ({s.declared}) |")
    t = fill_block(t, "INDICATORS", "\n".join(rows))
    sp = ["| Scenario | Prior (subjective) | Signposts |", "|---|---|---|"]
    for k, (name, prior, sps) in SCENARIOS.items():
        sp.append(f"| **{k}. {name}** | {prior:.0%} | " + " · ".join(f"{'/'.join(x.codes)}: {md_escape(x.label)}" for x in sps) + " |")
    res = config.RESULTS_DIR / "scenarios.json"
    if res.exists():
        hist = json.loads(res.read_text())["history"]
        last = {}
        for h in hist:
            last[h["scenario"]] = h
        sp += ["", "Latest point-in-time weekly reading (`reports/results/scenarios.json`):", "",
               "| Scenario | Week ending | Signposts holding | Which | Gaps | State |", "|---|---|---|---|---|---|"]
        for k in SCENARIOS:
            h = last[k]
            sp.append(f"| {k} | {h['week_end']} | {h['holding']} of {h['of']} | {', '.join(h['which']) or '-'} | {', '.join(h['gaps']) or '-'} | {h['state']} |")
    t = fill_block(t, "SIGNPOSTS", "\n".join(sp))
    p.write_text(t)


def book_block() -> None:
    res = config.RESULTS_DIR / "backtests.json"
    if not res.exists():
        return
    bt = json.loads(res.read_text())
    lab = {"D1": "D1 pre-specified", "D2": "D2 revised", "D3": "D3 in-sample research"}
    rows = ["| Code | Strategy | Evidence | Since | CAGR | Sharpe | Deflated Sharpe | Max DD | Risk-matched benchmark Sharpe | Info ratio |", "|---|---|---|---|---|---|---|---|---|---|"]
    for b in bt["book"]:
        rows.append(f"| {b['Trial']} | {b['Name']} | {lab[b['Evidence']]} | {b['Start']} | {b['CAGR']:+.1%} | {b['Sharpe']:.2f} | {b['DSR']:.2f} | {b['MaxDD']:.0%} | {b['risk_matched_Sharpe']:.2f} ({b['Ref']}) | {b['IR_vs_risk_matched']:+.2f} |")
    rows += ["", f"Monthly returns, sqrt(12), excess over DTB3, net of costs; development sample to {bt['backtest_end']}. Deflated Sharpe uses all {bt['n_trials']} trials. Blends, attribution, four benchmarks, CVaR, recovery times and crisis correlations: [`reports/backtest_summary.md`](../reports/backtest_summary.md) and `reports/evidence/performance_risk.csv`."]
    p = DOCS / "03_strategy_book.md"
    p.write_text(fill_block(p.read_text(), "BOOK", "\n".join(rows)))


def main():
    book_block()
    framework_blocks()
    (DOCS / "05_specifications.md").write_text(specs_doc())
    (DOCS / "06_review_response.md").write_text(review_doc())
    print("wrote docs/05_specifications.md, docs/06_review_response.md")


if __name__ == "__main__":
    main()
